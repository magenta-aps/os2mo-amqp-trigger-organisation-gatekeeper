class _NoopAMQPSystem:
    """Stand-in for MOAMQPSystem that does not consume any messages."""

    async def __aenter__(self) -> "_NoopAMQPSystem":
        return self

    async def __aexit__(self, *args: Any) -> None:
        return None


@pytest.fixture
def disable_amqp() -> None:
    """Explicitly request that the AMQP event system be disabled for a test."""


@pytest.fixture
async def app(
    request: pytest.FixtureRequest, monkeypatch: pytest.MonkeyPatch
) -> FastAPI:
    if "disable_amqp" in request.fixturenames:
        monkeypatch.setattr(
            "orggatekeeper.main.MOAMQPSystem",
            lambda *args, **kwargs: _NoopAMQPSystem(),
        )
    return create_app()


