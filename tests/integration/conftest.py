# autouse because the integration does not function if these are not pre-defined
@pytest.fixture(autouse=True)
async def org_unit_hierarchy_classes(
    graphql_client: GraphQLClient,
    org_unit_hierarchy_facet: CreateFacetFacetCreate,
) -> dict[str, UUID]:
    """
    Creates all the "org unit hierarchy" classes that this integration expects
    """

    user_keys = [
        "linjeorg",
        "selvejet",
        "hide",
        "NA",
    ]

    classes: dict[str, UUID] = {}
    for user_key in user_keys:
        res = await graphql_client.create_class(
            ClassCreateInput(
                name=user_key,
                user_key=user_key,
                facet_uuid=org_unit_hierarchy_facet.uuid,
                validity=ValidityInput(),
            )
        )
        classes[user_key] = res.uuid

    return classes


